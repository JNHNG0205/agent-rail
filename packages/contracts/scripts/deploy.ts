import { writeFileSync } from "node:fs";
import { join } from "node:path";
import hre from "hardhat";

/// Deploys all AgentRail contracts to the target network and writes their
/// addresses into packages/shared/src/addresses.ts so every consumer imports
/// one source of truth. Run with: npm run deploy (targets localhost).
async function main() {
  const usdc = await hre.viem.deployContract("MockUSDC");
  const jobContract = await hre.viem.deployContract("JobContract", [usdc.address]);
  const identityRegistry = await hre.viem.deployContract("IdentityRegistry");
  const reputationRegistry = await hre.viem.deployContract("ReputationRegistry");
  const evaluatorModule = await hre.viem.deployContract("EvaluatorModule", [jobContract.address]);

  const addresses = {
    MockUSDC: usdc.address,
    JobContract: jobContract.address,
    IdentityRegistry: identityRegistry.address,
    ReputationRegistry: reputationRegistry.address,
    EvaluatorModule: evaluatorModule.address,
  };

  const out = join(__dirname, "..", "..", "shared", "src", "addresses.ts");
  writeFileSync(
    out,
    `// AUTO-GENERATED by packages/contracts/scripts/deploy.ts — do not edit by hand.\n` +
      `export const addresses = ${JSON.stringify(addresses, null, 2)} as const;\n\n` +
      `export type ContractName = keyof typeof addresses;\n`
  );

  console.log("Deployed:", addresses);
  console.log("Wrote addresses ->", out);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
